"""Generate docs/release_recommendation.md and docs/incident_report.md from artifacts.

Every number comes from an artifact and carries its provenance label.
"""

from __future__ import annotations

import json
from typing import Any

from control_plane.monitoring import MONITORING_DIR, SHADOW_DIR
from control_plane.triage.activation import releases
from control_plane.triage.dataset import REPO_ROOT

RECOMMENDATION = REPO_ROOT / "docs" / "release_recommendation.md"
INCIDENT_REPORT = REPO_ROOT / "docs" / "incident_report.md"
NAMES = {
    "classifier_v1": "classifier_v1 (TF-IDF + logistic regression)",
    "llm_low_cost_v1": "llm_low_cost_v1 (gemini-3.1-flash-lite)",
    "llm_high_capability_v1": "llm_high_capability_v1 (gemini-3.8-flash)",
}


def _gate_rows(gates: list[dict[str, Any]]) -> list[str]:
    rows = ["| Gate | Threshold | Observed | Result |", "|---|---|---|---|"]
    for g in gates:
        op = g.get("comparison", ">=")
        observed = "n/a" if g["observed"] is None else f"{g['observed']:.3f}"
        rows.append(
            f"| {g['gate']} | {op} {g['threshold']:.3f} | {observed} `MEASURED` | "
            f"{'pass' if g['passed'] else 'FAIL'} |"
        )
    return rows


def shadow_summary(ref: str | None) -> dict[str, Any] | None:
    if not ref:
        return None
    path = REPO_ROOT / ref / "summary.json"
    return json.loads(path.read_text()) if path.exists() else None


def release_recommendation() -> str:
    recs = sorted(releases(), key=lambda r: r["proposed_at"])
    main = next((r for r in recs if r["candidate_config_id"] == "llm_high_capability_v1"), None)
    if main is None:
        raise RuntimeError("no release proposal for llm_high_capability_v1")
    shadow = shadow_summary(main.get("shadow_ref"))
    full = main["full_candidate"]
    cohort = main["cohort_candidate"]
    full_pass = sum(g["passed"] for g in full["gates"])
    cohort_pass = sum(g["passed"] for g in cohort["gates"])
    sc = full["scorecard"]
    lines = [
        "# Release recommendation: Support Triage",
        "",
        "Generated by `cp release report` from `artifacts/releases/` and `artifacts/shadow/`.",
        "",
        "## Recommendation in five sentences",
        "",
    ]
    t = shadow["totals"] if shadow else None
    summary = json.loads((REPO_ROOT / "artifacts" / "experiment_summary.json").read_text())
    base_ood = summary["configs"]["classifier_v1"]["scorecard"][
        "risk_route_accuracy.out_of_domain"
    ]["value"]
    sens_fail = [
        g for g in full["gates"] if g["gate"].startswith("sensitive_recall.") and not g["passed"]
    ]
    lowest = min((g["observed"] for g in sens_fail), default=None)
    sentences = [
        f"Keep classifier_v1 authoritative and withhold activation of gemini-3.8-flash: it "
        f"passes {full_pass} of {len(full['gates'])} release gates as a full candidate and "
        f"{cohort_pass} of {len(cohort['gates'])} as the proposed cohort `MEASURED`.",
        f"Its macro F1 is {sc['macro_f1']['value']:.3f} against a floor of "
        f"{next(g['threshold'] for g in full['gates'] if g['gate'] == 'macro_f1'):.3f} "
        f"`MEASURED`, and {len(sens_fail)} sensitive intents miss the 0.95 recall gate, the "
        f"lowest at {lowest:.2f} `MEASURED`.",
        f"Where the two models agree, auto-routed precision rises to "
        f"{sc['auto_precision']['value']:.3f} `MEASURED`, and the LLM routes "
        f"{sc['risk_route_accuracy.out_of_domain']['value']:.0%} of out-of-domain risk cases "
        f"to abstain against {base_ood:.0%} for the classifier `MEASURED`.",
    ]
    if t:
        sentences.append(
            f"In shadow, the models agreed on {t['label_agreement']:.1%} of labels over "
            f"{t['cases']:,} cases `SIMULATED`, at {t['candidate_cost_usd']:.2f} USD of model "
            f"spend `MEASURED`, and the proposed cohort would have produced "
            f"{t['net_value_usd']['cohort'] - t['net_value_usd']['approved']:+,.0f} USD of net "
            "value over the 14 days compared with the classifier alone `ASSUMPTION`."
        )
    else:
        sentences.append("Shadow replay has not run yet.")
    sentences.append(
        "The next investment is targeted: fix the sensitive-intent confusions (card payment "
        "versus direct debit) and re-evaluate, rather than spending on a larger model."
    )
    lines += [
        " ".join(sentences),
        "",
        "## Decisions recorded",
        "",
        "| Release | Candidate | Decision | By | Rationale |",
        "|---|---|---|---|---|",
    ]
    for r in recs:
        lines.append(
            f"| {r['release_id']} | {NAMES.get(r['candidate_config_id'])} | "
            f"{r['decision'] or 'pending'} | {r['decided_by'] or ''} | "
            f"{(r['rationale'] or '').replace('|', '/')} |"
        )
    lines += [
        "",
        "## Gates: gemini-3.8-flash as a full candidate",
        "",
        *_gate_rows(full["gates"]),
        "",
        f"## Gates: proposed cohort ({len(main['cohort'])} intents; excludes "
        f"{', '.join(main['cohort_excluded'])})",
        "",
        "Inside the cohort the candidate is authoritative; every other case stays on "
        "classifier_v1. Routing keys on classifier_v1's predicted intent.",
        "",
        *_gate_rows(cohort["gates"]),
        "",
    ]
    if shadow:
        lines += [
            "## Shadow replay (14 simulated days)",
            "",
            f"Run `{shadow['run_id']}`, authoritative `{shadow['authoritative_config_id']}`, "
            f"candidate `{shadow['candidate_config_id']}` on `{shadow['backend']}`.",
            "",
            "| Day | Cases | Label agreement | Route agreement | Candidate cost (USD) | "
            "Net value: classifier | Net value: cohort |",
            "|---|---|---|---|---|---|---|",
        ]
        for d in shadow["days"]:
            lines.append(
                f"| {d['day']} | {d['cases']} | {d['label_agreement']:.1%} | "
                f"{d['route_agreement']:.1%} | {d['candidate_cost_usd']:.4f} | "
                f"{d['net_value_usd']['approved']:,.0f} | "
                f"{d['net_value_usd']['cohort']:,.0f} |"
            )
        lines += [
            "",
            "Agreement and accuracy are `SIMULATED`; model cost is `MEASURED`; net value "
            "is `ASSUMPTION` (configs/business_model.yaml).",
            "",
        ]
    lines += [
        "## What did not match the intended demo story",
        "",
        "The specification's signature scenario expects the low-cost config to pass the "
        "overall gates and fail one sensitive intent. Measured results differ: both LLM "
        "configs fail macro F1 and several sensitive intents, and the cohort that excludes "
        "the failing intents still fails. The recorded decisions follow the measured "
        "numbers. No activation was recorded, so monitoring and the incident drill run on "
        "classifier_v1, which stays in production (docs/incident_report.md).",
        "",
    ]
    text = "\n".join(lines)
    RECOMMENDATION.write_text(text)
    return text


def incident_report() -> str:
    drills = sorted(MONITORING_DIR.glob("drill_*.json"))
    if not drills:
        raise RuntimeError("no drill has run; use cp drill")
    drill = json.loads(drills[-1].read_text())
    policy = json.loads((MONITORING_DIR / f"{drill['alert_policy']}.json").read_text())
    inc = drill["incident"]
    lines = [
        "# Incident report: Support Triage drift drill",
        "",
        "Generated by `cp drill` from `artifacts/monitoring/` and `artifacts/incidents/`.",
        "",
        "Production configuration: classifier_v1 (no LLM activation was approved; see "
        "docs/release_recommendation.md). Baseline traffic is the shadow pool `SIMULATED`; the "
        f"{drill['drift_cases']} drift cases on days {drill['drill_days'][0]} to "
        f"{drill['drill_days'][-1]} are `FIXTURE` (data/drift_cases.jsonl, authored by one rater).",
        "",
        "## Alert policy (frozen before the drill)",
        "",
        f"Policy `{policy['policy_id']}`, frozen {policy['frozen_at']}, from days "
        f"{policy['baseline_days'][0]} to {policy['baseline_days'][1]}.",
        "",
        "| Signal | Direction | Baseline mean | Baseline SD | Threshold |",
        "|---|---|---|---|---|",
    ]
    for k, t in policy["thresholds"].items():
        lines.append(
            f"| {k} | {t['direction']} | {t['baseline_mean']:.4f} | "
            f"{t['baseline_sd']:.4f} | {t['value']:.4f} `SIMULATED` |"
        )
    lines += ["", "## Outcome", ""]
    if inc:
        lines.append(
            f"Monitoring opened incident `{inc['incident_id']}` on simulated day "
            f"{inc['opened_day']}: {inc['signal']} observed {inc['observed']:.4f} against a "
            f"threshold of {inc['threshold']:.4f}. Detection delay: "
            f"{inc['detection_delay_days']} simulated day(s) after the drift began `MEASURED`, "
            f"{inc['detection_processing_seconds']:.3f} seconds of processing `MEASURED`. Final "
            f"status: {inc['status']}."
        )
    else:
        lines.append(
            "Monitoring did not detect the drift with the frozen thresholds. This is the "
            "measured result and is reported as such."
        )
    lines += [
        "",
        "## Timeline",
        "",
        "| Simulated day | Event | Actor | Detail |",
        "|---|---|---|---|",
    ]
    for e in drill["timeline"]:
        lines.append(f"| {e['day']} | {e['event']} | {e['actor']} | {e['detail']} |")
    lines += [
        "",
        "## Daily signals",
        "",
        "| Day | Cases | Drift cases | Authority | Review rate | Cost per correct (USD) | "
        "Sampled accuracy | Breaches |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for d in drill["days"]:
        acc = "n/a" if d["sampled_accuracy"] is None else f"{d['sampled_accuracy']:.3f}"
        cost = "n/a" if d["cost_per_correct_usd"] is None else f"{d['cost_per_correct_usd']:.3f}"
        lines.append(
            f"| {d['day']} | {d['cases']} | {d['drift_cases']} | {d['authority']} | "
            f"{d['review_rate']:.3f} | {cost} | {acc} | "
            f"{', '.join(b['signal'] for b in d['breaches']) or '—'} |"
        )
    by_cat: dict[str, dict[str, int]] = {}
    for r in drill["drift_rows"]:
        c = by_cat.setdefault(
            r["category"], {"cases": 0, "auto": 0, "review": 0, "candidate_out_of_scope": 0}
        )
        c["cases"] += 1
        c[r["approved_route"]] = c.get(r["approved_route"], 0) + 1
        c["candidate_out_of_scope"] += r.get("candidate_label") == "out_of_scope"
    lines += [
        "",
        "## How the drift cases were routed by classifier_v1 `FIXTURE`",
        "",
        "| Category | Cases | Auto-routed | Reviewed | Shadow LLM said out_of_scope |",
        "|---|---|---|---|---|",
    ]
    for cat, c in by_cat.items():
        lines.append(
            f"| {cat} | {c['cases']} | {c['auto']} | {c['review']} | "
            f"{c['candidate_out_of_scope']} |"
        )
    lines += ["", "## Findings", ""]
    if inc:
        margin = inc["observed"] - inc["threshold"]
        lines.append(
            f"- Detection was narrow: {inc['signal']} exceeded its threshold by {margin:.4f} "
            f"`MEASURED`. No other signal breached on day {inc['opened_day']}. A smaller drift "
            "would likely go unnoticed by these thresholds, so the alert design needs a "
            "drift-specific signal."
        )
    auto_sensitive = [
        r
        for r in drill["drift_rows"]
        if r["category"] == "sensitive_paraphrase" and r["approved_route"] == "auto"
    ]
    ood = [r for r in drill["drift_rows"] if r["category"] == "out_of_domain"]
    ood_llm = sum(r.get("candidate_label") == "out_of_scope" for r in ood)
    lines.append(
        f"- classifier_v1 auto-routed {len(auto_sensitive)} sensitive paraphrase(s) that a "
        "person should have handled `FIXTURE`, the costliest kind of misroute in the "
        "business model."
    )
    lines.append(
        f"- In shadow, gemini-3.8-flash labeled {ood_llm} of {len(ood)} out-of-domain drift "
        "cases out_of_scope `FIXTURE`, where the classifier cannot abstain. An out-of-scope "
        "guard is the strongest measured argument for a narrowly scoped LLM role."
    )
    lines += [
        "",
        "Signals are `SIMULATED` (shadow traffic) or `FIXTURE` (drift cases). Rollback in "
        "this deployment pauses automation so every case goes to human review; automation "
        "resumes only after a shadow check passes every threshold.",
        "",
    ]
    text = "\n".join(lines)
    INCIDENT_REPORT.write_text(text)
    return text


__all__ = ["SHADOW_DIR", "incident_report", "release_recommendation"]
